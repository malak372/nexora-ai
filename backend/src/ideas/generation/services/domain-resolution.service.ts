  private normalizeAutoDomainIdentityToken(value: string): string {
    let token = value.toLocaleLowerCase();
    if (token.length > 7 && token.endsWith('ing')) {
      token = token.slice(0, -3);
    } else if (token.length > 6 && token.endsWith('ers')) {
      token = token.slice(0, -3);
    } else if (token.length > 5 && token.endsWith('ies')) {
      token = `${token.slice(0, -3)}y`;
    } else if (token.length > 5 && token.endsWith('s')) {
      token = token.slice(0, -1);
    }
    return token;
  }

  private tokenIntersectionSize(
    left: ReadonlySet<string>,
    right: ReadonlySet<string>,
  ): number {
    let count = 0;
    for (const token of left) {
      if (right.has(token)) count += 1;
    }
    return count;
  }

  private normalizePlannedDomainName(value?: string): string | null {
    const normalized = value
      ?.normalize('NFKC')
      .replace(/[-_/]+/gu, ' ')
      .replace(/\s+/gu, ' ')
      .replace(/[.!?,;:]+$/gu, '')
      .replace(/\b(?:and|or|with|for|of|to|from|in|at|by|via)\s*$/giu, '')
      .replace(/\s+/gu, ' ')
      .trim();

    if (!normalized || normalized.length > 80) return null;
    const words = normalized.split(/\s+/u).filter((word) => word !== '&');
    if (words.length < 2 || words.length > 12) return null;
    if (
      /^(?:people|users|companies|travelers|travellers|members|owners|teams?|students?)\b/iu.test(
        normalized,
      ) ||
      /\b(?:often|struggle|struggles|want to|need to|who|regularly)\b/iu.test(
        normalized,
      )
    ) {
      return null;
    }

    return normalized;
  }

  private plannedDomainNameMatchesRequesterText(
    domainName: string,
    description?: string,
  ): boolean {
    const requesterText = description?.trim();
    if (!requesterText) return true;

    const domainIdentity = this.autoDomainIdentityTokens([domainName]);
    if (domainIdentity.size === 0) return false;
    const requesterIdentity = this.autoDomainIdentityTokens([requesterText]);
    if (requesterIdentity.size === 0) return false;

    return this.tokenIntersectionSize(domainIdentity, requesterIdentity) >= 1;
  }

