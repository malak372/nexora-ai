  /**
   * Selects a deterministic system fallback.
   *
   * The least-used active concrete domain is chosen to avoid permanently
   * favoring the first database row and to improve platform-wide diversity.
   */
  private async resolveSystemFallback(
    domains: readonly DomainCandidate[],
  ): Promise<DomainResolutionResult> {
    let usage: Array<{ domainId: string; _count: { _all: number } }> = [];

    // Keep Prisma's groupBy generic inference isolated from the generic retry
    // wrapper. Passing groupBy directly as the callback lets TypeScript
    // contextually infer Prisma's argument generic from the wrapper result
    // type, which can incorrectly intersect the GroupBy args with the result
    // array type (TS2345). The local async reader preserves the exact same
    // single SQL aggregation while allowing Prisma to infer its own payload
    // before it is wrapped by the transient-read retry.
    const readDomainUsage = async () => {
      const rows = await this.prisma.idea.groupBy({
        by: ['domainId'],
        where: {
          deletedAt: null,
          domainId: {
            in: domains.map((domain) => domain.id),
          },
        },
        _count: {
          _all: true,
        },
      });

      return rows;
    };

    try {
      usage = await this.executeTransientReadRetry(
        'domain usage fallback ranking',
        readDomainUsage,
      );
    } catch (error: unknown) {
      if (!isTransientDatabaseError(error)) throw error;
      // Usage balancing is a nice-to-have personalization/detail signal, not a
      // correctness requirement. If the DB is briefly unavailable, preserve
      // the already-loaded active domain set and choose deterministically.
      this.logger.warn(
        'Domain-usage lookup remained unavailable after bounded reconnect; continuing with deterministic catalog ordering.',
      );
    }

    const usageByDomainId = new Map(
      usage.map((item) => [item.domainId, item._count._all]),
    );

    const selectedDomain = [...domains].sort((first, second) => {
      const firstUsage = usageByDomainId.get(first.id) ?? 0;
      const secondUsage = usageByDomainId.get(second.id) ?? 0;

      return firstUsage - secondUsage || first.name.localeCompare(second.name);
    })[0];

    if (!selectedDomain) {
      throw new BadRequestException('No active concrete domain is configured.');
    }

    return {
      domainId: selectedDomain.id,
      domainName: selectedDomain.name,
      source: DomainResolutionSource.SYSTEM_DEFAULT,
      confidence: 0.25,
      trace: {
        reasons: [
          'No explicit request, saved domain preference, or usable user-history signal was available; the deterministic least-used-domain fallback was used.',
        ],
        matchedInterests: [],
        candidates: [
          {
            domainId: selectedDomain.id,
            domainName: selectedDomain.name,
            score: 0.25,
            reasons: ['Deterministic system fallback'],
          },
        ],
      },
    };
  }

  /**
   * Personalization must never turn a short Supabase/pooler interruption into
   * a failed NO_INPUT run. Retry one time after reconnect, then treat optional
   * preference/history data as unavailable for this run. Current request text,
   * explicit domains, active catalog identity, and later persistence remain
   * strict and authoritative.
   */
  private async resolveOptionalPersonalizationRead<T>(
    operationName: string,
    operation: () => Promise<T | null>,
  ): Promise<T | null> {
    try {
      return await this.executeTransientReadRetry(operationName, operation);
    } catch (error: unknown) {
      if (!isTransientDatabaseError(error)) throw error;
      this.logger.warn(
        `Skipping optional ${operationName} after bounded transient database recovery; domain resolution will continue with the next deterministic signal.`,
      );
      return null;
    }
  }

  /**
   * One reconnect + one retry is enough on the latency-sensitive PREPARING
   * path. Longer outages are handled by the pipeline's durable RETRYING state;
   * multiplying Prisma's own connection timeout here would only make the user
   * wait longer without increasing correctness.
   */
  private async executeTransientReadRetry<T>(
    operationName: string,
    operation: () => Promise<T>,
  ): Promise<T> {
    try {
      return await operation();
    } catch (error: unknown) {
      if (!isTransientDatabaseError(error)) throw error;

      this.logger.warn(
        `Transient database failure during ${operationName}; reconnecting once before retry.`,
      );
      try {
        await this.prisma.recoverConnection(error);
      } catch (recoveryError: unknown) {
        this.logger.warn(
          `Prisma reconnect did not complete cleanly during ${operationName}: ${
            recoveryError instanceof Error
              ? recoveryError.message
              : String(recoveryError)
          }`,
        );
      }
      return operation();
    }
  }

