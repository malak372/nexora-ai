  private domainLabelMatchesRequest(
    domainName: string,
    description: string,
  ): boolean {
    const domainTokens = this.semanticTokens(domainName);
    const requestTokens = this.semanticTokens(description);
    if (domainTokens.size === 0 || requestTokens.size === 0) return false;

    const ignored = new Set([
      'operations',
      'operation',
      'management',
      'workflow',
      'tracking',
      'platform',
      'client',
      'service',
      'services',
    ]);
    const meaningfulDomainTokens = [...domainTokens].filter(
      (token) => !ignored.has(token),
    );
    if (meaningfulDomainTokens.length === 0) return false;

    const overlap = meaningfulDomainTokens.filter((token) =>
      requestTokens.has(token),
    ).length;
    return overlap >= Math.min(2, meaningfulDomainTokens.length);
  }

  private planRemainsGrounded(
    plan: RequestCollectionPlan,
    description: string,
  ): boolean {
    const requestTokens = this.semanticTokens(description);
    if (requestTokens.size === 0) return false;

    const plannedText = [
      plan.suggestedDomainName ?? '',
      ...plan.searchQueries,
      ...plan.evidenceTargets,
      ...plan.intentConcepts,
    ].join(' ');
    const plannedTokens = this.semanticTokens(plannedText);
    const overlap = [...plannedTokens].filter((token) => requestTokens.has(token));

    const minimumOverlap = Math.min(
      4,
      Math.max(2, Math.ceil(requestTokens.size / 12)),
    );

    return overlap.length >= minimumOverlap;
  }

  private buildDeterministicFallback(
    description: string,
    keywords: readonly string[],
  ): RequestCollectionPlan {
    const combined = `${description} ${keywords.join(' ')}`.trim();
    const domainName =
      this.inferSpecializedProfessionalDomainName(combined) ??
      inferDominantRequestDomainName(combined) ??
      this.inferGenericProfessionalDomainName(combined);
    const concepts = this.extractConcepts(combined);
    const searchQueries = this.deduplicatePhrases([
      ...this.buildRequestQueries(description, concepts),
      ...RequestDynamicQueryUtil.buildEvidenceFacetQueries({
        requestDescription: description,
        intentConcepts: concepts,
        evidenceTargets: this.buildEvidenceTargets(description, concepts),
        maxQueries: 10,
      }),
    ]).slice(0, 14);

    return {
      selectedExistingDomainId: null,
      domainSelectionMode: 'NEW',
      suggestedDomainName: domainName,
      searchQueries,
      evidenceTargets: this.buildEvidenceTargets(description, concepts),
      intentConcepts: concepts.slice(0, 8),
      sourceFocus: this.inferSourceFocus(description),
      confidence: domainName ? 78 : 62,
      aiUsed: false,
      fallbackUsed: true,
    };
  }


