  private cleanRepeatedQueryTokens(value: string): string {
    const normalized = value
      .normalize('NFKC')
      .toLowerCase()
      .replace(/[^\p{L}\p{N}\s'-]+/gu, ' ')
      .replace(/\s+/gu, ' ')
      .trim();

    const output: string[] = [];
    for (const token of normalized.split(/\s+/u)) {
      if (output[output.length - 1] === token) continue;
      output.push(token);
    }

    /* Collapse immediately repeated phrases, not only repeated single tokens.
     * Example: "online marketplaces online marketplaces detect fraud". */
    for (let span = 4; span >= 1; span -= 1) {
      let index = 0;
      while (index + span * 2 <= output.length) {
        const first = output.slice(index, index + span).join(' ');
        const second = output.slice(index + span, index + span * 2).join(' ');
        if (first === second) {
          output.splice(index + span, span);
          continue;
        }
        index += 1;
      }
    }

    const boundaryFillers = new Set([
      'and', 'or', 'but', 'to', 'of', 'for', 'from', 'with', 'without',
      'into', 'across', 'between', 'while', 'because', 'about', 'on', 'in',
      'by', 'regarding', 'concerning',
    ]);
    while (output.length > 0 && boundaryFillers.has(output[0])) {
      output.shift();
    }
    while (
      output.length > 0 &&
      boundaryFillers.has(output[output.length - 1] ?? '')
    ) {
      output.pop();
    }

    return this.truncateAtBoundary(output.join(' '), 140);
  }

  private deduplicateQueries(values: readonly string[]): string[] {
    const output: string[] = [];
    const fingerprints: Array<Set<string>> = [];

    for (const raw of values) {
      const value = this.cleanRepeatedQueryTokens(raw);
      if (value.length < 8) continue;

      const tokens = this.semanticTokens(value);
      const duplicate = fingerprints.some((existing) => {
        const intersection = [...tokens].filter((token) => existing.has(token)).length;
        const denominator = Math.max(1, Math.min(tokens.size, existing.size));
        return intersection / denominator >= 0.82;
      });

      if (duplicate) continue;
      fingerprints.push(tokens);
      output.push(value);
    }

    return output;
  }

  private deduplicatePhrases(values: readonly string[]): string[] {
    const output: string[] = [];
    const seen = new Set<string>();

    for (const raw of values) {
      const value = raw
        .normalize('NFKC')
        .replace(/([\p{L}\p{N}])(?:['’]s)\b/giu, '$1')
        .replace(/(?:^|\s)['’]s\b/giu, ' ')
        .replace(/\s+/gu, ' ')
        .trim();
      if (!value) continue;
      const key = value.toLowerCase();
      if (seen.has(key)) continue;
      seen.add(key);
      output.push(value);
    }

    return output;
  }

  private truncateAtBoundary(value: string, maxLength: number): string {
    const cleaned = value.replace(/\s+/gu, ' ').trim();
    if (cleaned.length <= maxLength) return cleaned;
    const prefix = cleaned.slice(0, maxLength + 1);
    const sentenceMatches = [...prefix.matchAll(/(.+?[.!?])(?:\s|$)/gu)];
    const sentence = sentenceMatches.at(-1)?.[1]?.trim();
    if (sentence && sentence.length >= Math.floor(maxLength * 0.45)) {
      return sentence;
    }
    const wordBoundary = prefix
      .slice(0, maxLength)
      .replace(/\s+\S*$/u, '')
      .trim();
    return wordBoundary || cleaned.slice(0, maxLength).trim();
  }

  private normalizeStrings(
    value: unknown,
    maxItems: number,
    minLength: number,
    maxLength = 160,
  ): string[] {
    if (!Array.isArray(value)) return [];

    return this.deduplicatePhrases(
      value
        .filter((item): item is string => typeof item === 'string')
        .map((item) => this.truncateAtBoundary(item.replace(/\s+/gu, ' ').trim(), maxLength))
        .filter((item) => item.length >= minLength),
    ).slice(0, maxItems);
  }

